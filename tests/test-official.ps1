# Windows-hosted integration test: builds both engines from a tiny original
# fixture and installs the resulting official-tool PAF silently.
param(
  [string]$OfficialUrl='https://sourceforge.net/projects/portableapps/files/PortableApps.com%20Installer/PortableApps.comInstaller_3.9.24.paf.exe/download',
  [string]$OfficialSha256='7ef6e2758cb578843d767fb5fafdbde8bf872b84f0acd6e64f18afbb05c04f00'
)
$ErrorActionPreference='Stop'
. "$PSScriptRoot/../scripts/common.ps1"
Require ($IsWindows) 'Official-tool integration test requires Windows.'
$fixtureRoot=Join-Path $env:RUNNER_TEMP ('upb-vendor-smoke-'+[Guid]::NewGuid().ToString('N').Substring(0,10))
$src=Join-Path $fixtureRoot 'fixture/FixturePortable'
$out=Join-Path $fixtureRoot 'output'
$install=Join-Path $fixtureRoot 'installed/FixturePortable'
New-Item -ItemType Directory -Path (Join-Path $src 'App/AppInfo'),(Join-Path $src 'App/Fixture'),(Join-Path $src 'Other/Source'),(Join-Path $src 'Data/profile') -Force | Out-Null
Copy-Item -LiteralPath "$env:WINDIR/System32/where.exe" -Destination (Join-Path $src 'FixturePortable.exe')
Copy-Item -LiteralPath "$env:WINDIR/System32/where.exe" -Destination (Join-Path $src 'App/Fixture/fixture.exe')
Copy-Item -LiteralPath (Join-Path $PSScriptRoot 'fixture-icon.ico') -Destination (Join-Path $src 'App/AppInfo/appicon.ico')
@'
[Format]
Type=PortableApps.comFormat
Version=3.9
[Details]
Name=Fixture Portable
AppID=FixturePortable
Publisher=Portable Package Builder CI
Homepage=example.org
Category=Utilities
Description=Synthetic test application
Language=English
[Version]
DisplayVersion=1.0.0
PackageVersion=1.0.0.0
[License]
Shareable=true
OpenSource=false
Freeware=true
CommercialUse=true
[Control]
Start=FixturePortable.exe
'@ | Set-Content -LiteralPath (Join-Path $src 'App/AppInfo/appinfo.ini') -Encoding ascii
'Synthetic fixture material' | Set-Content -LiteralPath (Join-Path $src 'Other/Source/README.txt')
'Fixture EXE under App' | Set-Content -LiteralPath (Join-Path $src 'App/Fixture/README.txt')
'PRIVATE TEST DATA; MUST NOT SHIP' | Set-Content -LiteralPath (Join-Path $src 'Data/profile/private-marker.txt')
$original=(Get-FileHash -LiteralPath (Join-Path $src 'App/AppInfo/appinfo.ini') -Algorithm SHA256).Hash

try {
  & "$PSScriptRoot/../scripts/build.ps1" -SourceDir $src -OutputDir $out -Engine both -PackageRevision smoke -OfficialUrl $OfficialUrl -OfficialSha256 $OfficialSha256 -TimeoutSeconds 600
  $official=@(Get-ChildItem -LiteralPath $out -File -Filter '*_official-*.paf.exe')
  $custom=@(Get-ChildItem -LiteralPath $out -File -Filter '*_custom-nsis-*.paf.exe')
  Require ($official.Count -eq 1 -and $custom.Count -eq 1) 'Dual engine did not produce exactly two distinct PAF files.'
  Require ((Get-FileHash -LiteralPath (Join-Path $src 'App/AppInfo/appinfo.ini') -Algorithm SHA256).Hash -eq $original) 'Vendor build changed original source AppInfo.'
  Require (Test-Path -LiteralPath (Join-Path $src 'Data/profile/private-marker.txt')) 'Original user Data was modified.'
  $seven=Get-7zip
  $lines=@(& $seven l -slt $official[0].FullName)
  Require ($LASTEXITCODE -eq 0) 'Could not inspect generated official-tool PAF.'
  Require (($lines -join "`n") -notmatch '(?i)private-marker\.txt') 'Official PAF embedded private Data!'
  Write-Host 'PASS: Both PAFs generated by distinct engines; source unchanged; Data marker excluded.'
  New-Item -ItemType Directory -Path (Split-Path $install -Parent) -Force | Out-Null
  $psi=[Diagnostics.ProcessStartInfo]::new()
  $psi.FileName=$official[0].FullName
  $psi.UseShellExecute=$false
  $psi.CreateNoWindow=$true
  $psi.WindowStyle=[Diagnostics.ProcessWindowStyle]::Hidden
  [void]$psi.ArgumentList.Add('/S')
  [void]$psi.ArgumentList.Add("/D=$install")
  $proc=[Diagnostics.Process]::Start($psi)
  try {
    if(-not $proc.WaitForExit(180000)) { try { $proc.Kill($true) } catch {}; throw 'Official output PAF did not finish silent test installation within 180s.' }
    Require ($proc.ExitCode -eq 0) "Generated official PAF /S installation failed with exit $($proc.ExitCode)."
  } finally { $proc.Dispose() }
  Require (Test-Path -LiteralPath (Join-Path $install 'FixturePortable.exe') -PathType Leaf) 'Official installer omitted root portable launcher.'
  Require (Test-Path -LiteralPath (Join-Path $install 'App/AppInfo/appinfo.ini') -PathType Leaf) 'Official installer omitted AppInfo.'
  Require (Test-Path -LiteralPath (Join-Path $install 'App/Fixture/fixture.exe') -PathType Leaf) 'Official installer omitted application EXE.'
  Write-Host 'ALL PASS: vendor tool built official-format PAF and the produced package installed silently.'
} finally {
  Write-Host "Smoke test debug directory: $fixtureRoot"
  # Copy diagnostic vendor logs to persistent runner working directory on error.
  $logTarget=Join-Path $env:GITHUB_WORKSPACE 'official-smoke-diagnostics'
  $work=Join-Path $out '_upb_work'
  if(Test-Path $work) {
    New-Item -ItemType Directory -Path $logTarget -Force | Out-Null
    Get-ChildItem -LiteralPath $work -Recurse -File -Filter '*.log' | ForEach-Object {
      Copy-Item -LiteralPath $_.FullName -Destination (Join-Path $logTarget ($_.Directory.Name+'-'+$_.Name)) -Force
    }
  }
}
